    /**
     * Generates a natural, descriptive sentence describing what the model
     * is about to do based on the user's prompt.
     */
    fun initialDescription(prompt: String): String {
        val lower = prompt.lowercase(Locale.ROOT)
        return when {
            Regex("\\b(fix|bug|issue|crash|error|exception|broken|fail|failing|resolve)\\b").containsMatchIn(lower) ->
                "Analyzing the issue and planning a targeted fix…"
            Regex("\\b(test|verify|verification|check|assert|spec|coverage)\\b").containsMatchIn(lower) ->
                "Reviewing requirements and preparing verification steps…"
            Regex("\\b(implement|create|add|build|make|new|feature)\\b").containsMatchIn(lower) ->
                "Formulating implementation plan for the requested feature…"
            Regex("\\b(refactor|clean|simplify|restructure|optimize|speed|improve|cleanup)\\b").containsMatchIn(lower) ->
                "Analyzing structure and preparing refactoring plan…"
            Regex("\\b(find|search|locate|grep|where|look for|scan)\\b").containsMatchIn(lower) ->
                "Scanning workspace files and locating relevant code…"
            Regex("\\b(explain|why|how|what|document|describe|tell me|understand)\\b").containsMatchIn(lower) ->
                "Analyzing your question and organizing the explanation…"
            Regex("\\b(ui|screen|layout|compose|animation|style|theme|view|stutter|scroll)\\b").containsMatchIn(lower) ->
                "Evaluating UI behavior and formulating layout updates…"
            Regex("\\b(delete|remove|drop|prune)\\b").containsMatchIn(lower) ->
                "Checking dependencies and preparing safe cleanup…"
            Regex("\\b(run|build|compile|gradle|assemble|terminal|command)\\b").containsMatchIn(lower) ->
                "Reviewing build setup and preparing command execution…"
            else -> generalSentences[Math.abs(prompt.hashCode()) % generalSentences.size]
        }
    }

    /**
     * Returns an infinite sequence of shuffled thinking messages, ensuring variety.
     */
    fun shuffledSequence(): Sequence<String> = sequence {
        while (true) {
            val shuffled = ALL_MESSAGES.shuffled()
            for (msg in shuffled) {
                yield(if (msg.endsWith("…")) msg else "$msg…")
            }
        }
    }
